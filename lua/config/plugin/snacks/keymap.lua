vim.keymap.set("n", "`", function()
  require("snacks").explorer()
end, { desc = "File Explorer" })

-- rename current file (updates LSP references / imports)
vim.keymap.set("n", "<Leader>R", function()
  require("snacks").rename.rename_file()
end, { desc = "File: rename current file" })

-- buffer delete (preserves window layout, unlike :bd)
vim.keymap.set("n", "<Leader>q", function()
  require("snacks").bufdelete()
end, { desc = "Buffer: delete buffer" })
vim.keymap.set("n", "<Leader>qq", function()
  require("snacks").bufdelete.all()
end, { desc = "Buffer: delete all buffer" })
vim.keymap.set("n", "<Leader>qa", function()
  require("snacks").bufdelete.all({ force = true })
end, { desc = "Buffer: force delete all buffer" })
vim.keymap.set("n", "<Leader>qo", function()
  require("snacks").bufdelete.other()
end, { desc = "Buffer: delete all buffer except this one" })

-- picker
vim.keymap.set("n", "<Leader>0", function() require("snacks").picker.oldfiles() end, { desc = "Snacks: Lists previously open files" })
vim.keymap.set("n", "<Leader>o", function() require("snacks").picker.files() end, { desc = "Snacks: Open files" })
vim.keymap.set("n", "<Leader>m", function() require("snacks").picker.marks() end, { desc = "Snacks: Lists vim marks" })
vim.keymap.set("n", "<Leader><Leader>", function() require("snacks").picker() end, { desc = "Snacks: Open builtin function" })
vim.keymap.set("n", "<Leader>d", function() require("snacks").picker.diagnostics() end, { desc = "Snacks: Lists diagnostics" })
vim.keymap.set("n", "<Leader>a", function() require("snacks").picker.lsp_symbols() end, { desc = "Snacks: List LSP symbols" })
vim.keymap.set("n", "<Leader>l", function() require("snacks").picker.buffers() end, { desc = "Snacks: Lists buffers" })
vim.keymap.set("n", "<Leader>c", function() require("snacks").picker.commands() end, { desc = "Snacks: Lists commands" })
vim.keymap.set("n", "<Leader>r", function() require("snacks").picker.registers() end, { desc = "Snacks: Lists register" })
